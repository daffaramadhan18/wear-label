/**
 * Inline SVG icon set — only what the pages actually use.
 *
 * Two families, because the design draws two kinds of mark:
 *
 *   - The chrome icons (menu, close) are stroked at 1.5 on a 24px box.
 *   - The storefront icons imported from the design project (bag, account,
 *     heart, chevrons, arrow, and the three service marks) are solid shapes.
 *     They are inlined here with `fill="currentColor"` rather than shipped as
 *     files, so a hover or active state is a colour change on the parent and
 *     never a second network request for a recoloured copy of the same mark.
 *
 * Path data is taken verbatim from `assets/icons/*.svg` in the design project;
 * the source files' baked-in fills and their redundant mask/rect pairs are
 * dropped. Icons are decorative (`aria-hidden`) — when an icon is the only
 * content of a control, the control carries the accessible name. Never use emoji
 * as an icon.
 */

type IconProps = React.SVGProps<SVGSVGElement>;

/** Stroked, 24px box — the chrome family. */
function Icon({ children, ...props }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      width="24"
      height="24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

/**
 * Solid, `currentColor` — the storefront family. `viewBox` varies because the
 * source artwork does: the header marks are drawn on 16, the interface marks on
 * 24 and the service marks on 48. Rendered size comes from the caller's
 * className, so a 16-box mark and a 48-box mark still line up optically.
 */
function SolidIcon({
  box,
  children,
  ...props
}: IconProps & { box: 16 | 24 | 48 }) {
  return (
    <svg
      viewBox={`0 0 ${box} ${box}`}
      width={box}
      height={box}
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

